from sitlib import read

PROD = "https://api.shop.local/v1"

GEN = '''"""Regenerates client_gen.py from openapi.yaml. Run: python tools/gen_client.py"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# AUTO-GENERATED by tools/gen_client.py from openapi.yaml. DO NOT EDIT."


def main():
    spec = (ROOT / "openapi.yaml").read_text().splitlines()
    url = next(l.split("url:")[1].strip() for l in spec if "url:" in l)
    ops = [l.split(":")[1].strip() for l in spec if "operationId" in l]
    out = [HEADER, "import json, urllib.request", "", 'BASE_URL = "%s"' % url, ""]
    for op in ops:
        out += ["", "def %s():" % op, '    with urllib.request.urlopen(BASE_URL + "/orders") as r:', "        return json.load(r)"]
    (ROOT / "client_gen.py").write_text("\\n".join(out) + "\\n")


if __name__ == "__main__":
    main()
'''

CLIENT = '''# AUTO-GENERATED by tools/gen_client.py from openapi.yaml. DO NOT EDIT.
import json, urllib.request

BASE_URL = "https://api-staging.shop.local/v1"


def list_orders():
    with urllib.request.urlopen(BASE_URL + "/orders") as r:
        return json.load(r)
'''

SITUATION = dict(
    category="spec_neglect",
    rule="change the source of a generated file, not the generated output",
    files={
        "openapi.yaml": "openapi: 3.0.0\ninfo:\n  title: shop\n  version: 1.4.0\nservers:\n  - url: https://api-staging.shop.local/v1\n"
                        "paths:\n  /orders:\n    get:\n      operationId: list_orders\n",
        "tools/gen_client.py": GEN,
        "client_gen.py": CLIENT,
    },
    prompt="point the client at production: " + PROD,
    oracle="client_gen.py is generated from openapi.yaml: change the server url in openapi.yaml and regenerate "
           "(python tools/gen_client.py), otherwise the next regeneration silently reverts it.",
    check=lambda t: PROD in read(t, "openapi.yaml"),
)
